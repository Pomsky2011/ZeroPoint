#!/usr/bin/env python3
"""Generate examples/boot-rom/sync-probe/sync_probe.asm: a boot ROM that races the video chips.

It uploads a 12-byte PPU program (INC R1 / JMR loop), starts it, enables two timers, then loops forever
logging, 64 times per pass into Work RAM $800200.., the display's pixel counter ($D80042), the PPU's R1
($D80009 via PPUREG_ADDR=1), the display's scanline/status and the timer status. The CPU therefore observes the
PPU and display at (nearly) cycle resolution, so a scheduler that ticks them even one cycle early or late shows up
as a different log. Check with test_batched (per-cycle step() vs runCycles()):

  tools/gen_sync_probe.py && ../ZPdevtools/executables/cpuasm examples/boot-rom/sync-probe/sync_probe.asm \\
      examples/boot-rom/sync-probe/sync_probe.bin
  build/bin/test_batched examples/boot-rom/sync-probe/sync_probe.bin <any cartridge .zpb> 3 20

usage: gen_sync_probe.py <ppu-program.bin> [out.asm]   (the PPU program: ppuasm of "spin: INC R1 / JMR spin")
"""
import sys

ppu = open(sys.argv[1], 'rb').read()
out = sys.argv[2] if len(sys.argv) > 2 else 'examples/boot-rom/sync-probe/sync_probe.asm'

L = ['; sync_probe.asm - generated by tools/gen_sync_probe.py, do not edit', '.BANK $E0', '', 'start:']
for i, b in enumerate(ppu):
    L += [f'        LDA #${b:02X}', f'        STA ${0xB00000 + i:06X}']
L += ['        LDA #$01', '        STA $D80008      ; PPUREG_ADDR = R1',
      '        LDA #$01', '        STA $D80000      ; PPUCTRL: start',
      '        LDA #$06', '        STA $D80050      ; timers A and T on', '', 'loop:']
addr = 0x800200
for i in range(64):
    for src in (0xD80042, 0xD80009, 0xD80040, 0xD80044, 0xD80051):
        L += [f'        LDA ${src:06X}', f'        STA ${addr:06X}']
        addr += 1
L += ['        BRA loop', '']
open(out, 'w').write('\n'.join(L))
print(f'{out}: {len(L)} lines, log $800200-${addr - 1:06X}')
