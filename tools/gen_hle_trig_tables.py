#!/usr/bin/env python3
"""Regenerate src/boot_hle/trig_tables.h from ZPbootROM's trig_model.py (the source of the real Boot ROM's tables).

  tools/gen_hle_trig_tables.py [path/to/trig_model.py]     (default ../ZPbootROM/def88186/trig_model.py)
"""
import importlib.util
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
model_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "../../ZPbootROM/def88186/trig_model.py")
spec = importlib.util.spec_from_file_location("trig_model", model_path)
m = importlib.util.module_from_spec(spec)
spec.loader.exec_module(m)


def arr(name, vals):
    lines = ["    " + ", ".join(str(v) for v in vals[i:i + 12]) + "," for i in range(0, len(vals), 12)]
    return "constexpr int32_t %s[258] = {\n%s\n};\n" % (name, "\n".join(lines))


out = '''// Generated by tools/gen_hle_trig_tables.py from ZPbootROM/def88186/trig_model.py - do not edit.
// The same tables the real Boot ROM carries (patched into bank $E0 by its build.sh), as constants, so the HLE
// does not depend on the host's libm for them.
#pragma once
#include <cstdint>

namespace ZeroPoint {
namespace BootHLE {

// round(32767 * sin(i * pi/512)) for i = 0..256, entry 257 = entry 256
''' + arr("SIN_TAB", m.SIN_TAB) + '''
// round(atan(i/256) * 65536/2pi) for i = 0..256, entry 257 = entry 256
''' + arr("ATAN_TAB", m.ATAN_TAB) + '''
}  // namespace BootHLE
}  // namespace ZeroPoint
'''
open(os.path.join(here, "../src/boot_hle/trig_tables.h"), "w").write(out)
